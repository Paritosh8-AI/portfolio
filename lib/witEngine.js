// Helper to generate a unique hash signature for deduplication
export function hashJoke(joke) {
  const str = (joke.category + ':' + joke.text).toLowerCase().replace(/[^a-z0-9]/g, '');
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return hash.toString(36);
}

/**
 * Returns the next unique joke that hasn't been seen in the provided seenSet.
 * If all curated jokes are exhausted, it procedurally synthesizes fresh combinations indefinitely.
 */
export function getNextUniqueJoke(seenSet = new Set()) {
  // 1. Try to find an unseen curated joke first (shuffled order)
  const remainingCurated = CURATED_WIT.filter((j) => !seenSet.has(hashJoke(j)));

  if (remainingCurated.length > 0) {
    const randomIndex = Math.floor(Math.random() * remainingCurated.length);
    const chosen = remainingCurated[randomIndex];
    seenSet.add(hashJoke(chosen));
    return chosen;
  }

  // 2. Curated exhausted or requested fresh procedural: dynamically synthesize!
  let attempts = 0;
  while (attempts < 40) {
    attempts++;
    const generator = PROCEDURAL_GENERATORS[Math.floor(Math.random() * PROCEDURAL_GENERATORS.length)];
    const synthesized = generator();
    const h = hashJoke(synthesized);
    if (!seenSet.has(h)) {
      seenSet.add(h);
      return synthesized;
    }
  }

  // Fallback procedural with high-entropy guarantee
  const fallbackGen = PROCEDURAL_GENERATORS[Math.floor(Math.random() * PROCEDURAL_GENERATORS.length)];
  const joke = fallbackGen();
  seenSet.add(hashJoke(joke));
  return joke;
}

/**
 * Generates an initial pool of N unique jokes
 */
export function generateJokePool(count = 10) {
  const seen = new Set();
  const pool = [];
  for (let i = 0; i < count; i++) {
    pool.push(getNextUniqueJoke(seen));
  }
  return pool;
}
